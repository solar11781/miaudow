def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def render(root: Path, groups: list[tuple[str, str, str]]) -> str:
    """The list as Markdown: one section per group, its note, then each file's path and sha256, sorted by path."""
    lines = [HEADER]
    for folder, pattern, note in groups:
        files = sorted(p.relative_to(root).as_posix() for p in (root / folder).glob(pattern) if p.is_file())
        lines += ["", f"## {folder}", "", note, ""]
        lines += [f"- `{f}` {sha256_of(root / f)}" for f in files]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (REPO / OUT).write_text(render(REPO, GROUPS), encoding="utf-8", newline="\n")
